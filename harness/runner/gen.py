"""Generate `harness_gen.h` and `bench_main.cu` for one kernel snapshot."""

from __future__ import annotations

HARNESS_HEADER = """// Generated by kernel-harness. Buffer layout for `{kernel_id}`.
#pragma once
#include <cuda_runtime.h>
#include <cstdio>
#include <cstdlib>
#include <cstring>

struct HarnessParams {{
    void* buf[8];
    long dim[8];
}};

#define HARNESS_NBUF {nbuf}
#define HARNESS_OUT_INDEX {out_index}
#define HARNESS_DTYPE_IS_S32 {is_s32}

static const long kHarnessElems[HARNESS_NBUF] = {{{elems}}};
"""

BENCH = r"""// Generated by kernel-harness: benchmark driver for @@VARIANT@@.
#include "harness_gen.h"
@@SOURCE@@

static unsigned rngState = 0x9E3779B9u;
static inline unsigned xorshift32() {
    unsigned x = rngState;
    x ^= x << 13; x ^= x >> 17; x ^= x << 5;
    rngState = x;
    return x;
}

static void fillBuffer(void* p, size_t bytes) {
    if (HARNESS_DTYPE_IS_S32) {
        int* q = (int*)p;
        size_t n = bytes / sizeof(int);
        for (size_t i = 0; i < n; ++i) {
            unsigned w = xorshift32();
            q[i] = (int)((w >> 8) % 201u) - 100;
        }
    } else {
        float* q = (float*)p;
        size_t n = bytes / sizeof(float);
        for (size_t i = 0; i < n; ++i) {
            unsigned w = xorshift32();
            q[i] = (float)((double)(w >> 8) * (1.0 / 16777216.0) * 2.0 - 1.0);
        }
    }
}

static int cmpDouble(const void* a, const void* b) {
    double x = *(const double*)a, y = *(const double*)b;
    return (x < y) ? -1 : (x > y);
}

int main(int argc, char** argv) {
    const char* outPath = (argc > 1) ? argv[1] : "out.bin";
    const int warmup = (argc > 2) ? atoi(argv[2]) : 10;
    const int reps = (argc > 3) ? atoi(argv[3]) : 30;

    HarnessParams p;
    size_t bytes[HARNESS_NBUF];
    void* host[HARNESS_NBUF];
    memset(&p, 0, sizeof(p));
    for (int i = 0; i < HARNESS_NBUF; ++i) {
        p.dim[i] = kHarnessElems[i];
        bytes[i] = (size_t)kHarnessElems[i] * (HARNESS_DTYPE_IS_S32 ? sizeof(int) : sizeof(float));
        // Inputs are filled in host memory and copied in: device pointers are not
        // host-writable.
        host[i] = malloc(bytes[i] ? bytes[i] : 4);
        if (cudaMalloc(&p.buf[i], bytes[i] ? bytes[i] : 4) != cudaSuccess) {
            fprintf(stderr, "cudaMalloc failed for buffer %d\n", i);
            return 2;
        }
        if (i != HARNESS_OUT_INDEX) {
            fillBuffer(host[i], bytes[i]);
            cudaMemcpy(p.buf[i], host[i], bytes[i], cudaMemcpyHostToDevice);
        } else {
            memset(host[i], 0, bytes[i]);
            cudaMemset(p.buf[i], 0, bytes[i]);
        }
    }

    for (int i = 0; i < warmup; ++i) launch_kernel(p);
    cudaError_t err = cudaDeviceSynchronize();
    if (err != cudaSuccess) { fprintf(stderr, "launch failed: %s\n", cudaGetErrorString(err)); return 3; }

    double* times = (double*)malloc(sizeof(double) * (size_t)reps);
    cudaEvent_t start, stop;
    cudaEventCreate(&start); cudaEventCreate(&stop);
    for (int i = 0; i < reps; ++i) {
        cudaEventRecord(start);
        launch_kernel(p);
        cudaEventRecord(stop);
        cudaEventSynchronize(stop);
        float ms = 0.0f;
        cudaEventElapsedTime(&ms, start, stop);
        times[i] = (double)ms;
    }
    err = cudaGetLastError();
    if (err != cudaSuccess) { fprintf(stderr, "kernel error: %s\n", cudaGetErrorString(err)); return 4; }

    qsort(times, (size_t)reps, sizeof(double), cmpDouble);
    double p50 = times[reps / 2];
    double p90 = times[(int)(reps * 0.9) < reps ? (int)(reps * 0.9) : reps - 1];
    double mn = times[0];
    double mean = 0.0;
    for (int i = 0; i < reps; ++i) mean += times[i];
    mean /= reps;
    double var = 0.0;
    for (int i = 0; i < reps; ++i) var += (times[i] - mean) * (times[i] - mean);
    double sd = (reps > 1) ? sqrt(var / (reps - 1)) : 0.0;

    FILE* f = fopen(outPath, "wb");
    if (f) {
        cudaMemcpy(host[HARNESS_OUT_INDEX], p.buf[HARNESS_OUT_INDEX],
                   bytes[HARNESS_OUT_INDEX], cudaMemcpyDeviceToHost);
        fwrite(host[HARNESS_OUT_INDEX], 1, bytes[HARNESS_OUT_INDEX], f);
        fclose(f);
    }

    printf("HARNESS_RESULT {\"p50_ms\": %.6f, \"p90_ms\": %.6f, \"min_ms\": %.6f, \"std_ms\": %.6f,"
           " \"reps\": %d, \"warmup\": %d}\n", p50, p90, mn, sd, reps, warmup);
    return 0;
}
"""


def buffer_elems(kernel, env: dict[str, int]) -> list[int]:
    """Element counts per buffer, from the kernel's shape."""
    fam = kernel.family
    if fam == "elementwise":
        n = int(env.get("N", 1))
        return [n] * len(kernel.buffers)
    if fam == "gemm":
        m, k = int(env.get("M", 8)), int(env.get("K", 8))
        n = int(env.get("N_out", 8))
        sizes = {"A": m * k, "B": k * n, "C": m * n}
        return [sizes.get(b.upper(), m * n) for b in kernel.buffers]
    if fam == "attention":
        rows, t, d = int(env["N_rows"]), int(env["T"]), int(env["D"])
        sizes = {"Q": rows * d, "K": t * d, "V": t * d, "OUT": rows * d}
        return [sizes.get(b.upper(), rows * d) for b in kernel.buffers]
    n = int(env.get("N", 1))
    return [n] * len(kernel.buffers)


def harness_header(kernel, env: dict[str, int], buffers: list[str]) -> str:
    elems = ", ".join(str(e) for e in buffer_elems(kernel, env))
    return HARNESS_HEADER.format(
        kernel_id=kernel.id,
        nbuf=len(buffers),
        out_index=kernel.out_index,
        is_s32=1 if kernel.dtype in ("s32", "i32") else 0,
        elems=elems,
    )


def bench_driver(source: str, variant_id: str) -> str:
    return BENCH.replace("@@SOURCE@@", source).replace("@@VARIANT@@", variant_id)


def build_profile_job(variant, gpu: str, *, reps: int, warmup: int):
    """Build the `ProfileJob` a backend needs to compile, time and check `variant`."""
    from ..backends.base import ProfileJob
    from ..registry import geometry

    kernel = variant.kernel
    env = kernel.shape_env()
    geom = geometry(kernel)
    bytes_moved, flops = kernel.sol_numbers(env)
    return ProfileJob(
        variant_id=variant.id,
        gpu=gpu,
        source=variant.source,
        harness_header=harness_header(kernel, env, kernel.buffers),
        shape={
            "N": env.get("N", 0),
            "M": env.get("M", 0),
            "K": env.get("K", 0),
            "N_out": env.get("N_out", env.get("K", 0)),
            "N_rows": env.get("N_rows", 0),
            "T": env.get("T", 0),
            "D": env.get("D", 0),
        },
        tol=kernel.tol,
        reps=reps,
        warmup=warmup,
        baseline=kernel.baseline,
        bytes_moved=bytes_moved,
        flops=flops,
        sol_kind=kernel.sol.kind,
        out_index=kernel.out_index,
        buffers=kernel.buffers,
        dtype=kernel.dtype,
        family=kernel.family,
        grid=geom["grid"],
        block=geom["block"],
        extra={
            "level": variant.level,
            "family": variant.family,
            "transforms": list(variant.params.keys()),
            "reference": kernel.extra.get("reference"),
        },
    )
